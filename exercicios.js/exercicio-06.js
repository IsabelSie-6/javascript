//* 6. (Verdadeiro ou Falso) Na sintaxe
//  for (inicialização; condição; incremento), 
// a parte da 'condição' é verificada apenas uma vez, logo no início do laço.  
// ( ) Verdadeiro  (X) Falso. 

// Essa afirmação é falsa, porque a condição não é verificada só uma vez, ela é verificada em cada repetição, independente de quantas são.

for (let i = 1; i <= 4; i++)
{ console.log("JavaScript"); } 

//  i <= 4 por exemplo é uma condição que é verificada até chegar no fim, que seria um número maior que quatro. 
