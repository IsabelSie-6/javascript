//* 18. (Verdadeiro ou Falso) Em JavaScript, o número 0 (zero) é avaliado como um valor falso (falsy).
//  (X) Verdadeiro  ( ) Falso *//

let numero = 0;
if (numero) { 
    console.log("Verdadeiro.")
} else {
    console.log("Falso.")
} 

//* Zero é falsy porque no JavaScript ele é interpretado como falso em alguma condição.